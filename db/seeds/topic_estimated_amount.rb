    <div style="background:#e0e7ff;padding:12px;border-radius:8px;margin:8px 0;">
    <strong>시행규칙 제2조 제2호 (추정금액)</strong><br>
    시행령 제2조제1호에 따른 <strong>추정가격</strong>에 「부가가치세법」에 따른 <strong>부가가치세</strong>와 <strong>관급자재</strong>(계약상대자가 설치하는 관급자재로 한정한다)로 공급될 부분의 가격을 <strong>합한 금액</strong>을 말한다.
    </div>

    추정가격이 "관급자재·부가세를 뺀 순수 도급액"이라면, 추정금액은 그 위에 **부가세와 관급자재를 다시 더한 총사업 규모**입니다.

    <div style="background:#ecfeff;padding:12px;border-radius:8px;margin:8px 0;">
    <strong>📐 계산 예시</strong><br>
    어떤 공사의 순수 도급 부분(관급자재 제외)이 <strong>3억원</strong>, 계약상대자가 설치할 관급자재가 <strong>2천만원</strong>이라면:<br>
    · 추정가격 = <strong>3억원</strong> (관급자재 제외)<br>
    · 추정금액 = 3억원 + 부가가치세 3천만원 + 관급자재 2천만원 = <strong>3억5천만원</strong>
    </div>

    ### 왜 두 값을 따로 쓰나
    - **추정가격**: 계약방법·국제입찰·공고기간 판단 → "부가세 빼고, 순수 경쟁 대상 규모"를 봐야 하므로
    - **추정금액**: 적격심사의 공사규모 구분 등 → "실제 투입되는 총사업비 규모"를 봐야 하므로

    > 입찰공고·계약서에 두 값이 함께 표기되는 경우가 많습니다. **어느 기준을 쓰는 규정인지** 확인하는 것이 실무의 핵심입니다.
