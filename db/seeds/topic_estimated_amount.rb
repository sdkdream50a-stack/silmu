  t.regulation_content = <<~CONTENT
    ## 실무 핵심 — 헷갈리지 않으려면

    ### ① 추정가격에는 부가가치세를 포함하지 않습니다
    추정가격은 부가세 제외 금액입니다. 수의계약 한도(2천만원 등)도 **부가세 제외 추정가격** 기준입니다. 부가세 포함 금액으로 한도를 판단하면 오류입니다.

    ### ② 관급자재 처리 방향이 반대입니다
    - 추정가격: 관급자재 **제외**
    - 추정금액: 관급자재(계약상대자 설치분) **포함**

    ### ③ 분할계약 금지 (시행령 §77)
    수의계약 한도나 입찰 방식을 회피하려고 단일 사업을 쪼개는 것은 금지됩니다. 목적·기간·이행자가 실질적으로 같으면 **하나의 계약**으로 봅니다. 추정가격을 인위적으로 낮추는 분할은 중징계·형사책임 대상이 될 수 있습니다.

    ### ④ 추정가격 → 예정가격 순서
    추정가격은 예정가격이 결정되기 **전에** 산정합니다(§2 1호). 예정가격은 입찰·계약 직전에 작성하는 낙찰 기준선입니다(§2 2호). 두 값을 같은 것으로 취급하지 마세요.
