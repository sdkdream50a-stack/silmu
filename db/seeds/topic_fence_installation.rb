    ## 지방계약법 시행규칙 제33조 (견적서 제출 생략의 대상)

    <div style="background:#fef3c7;padding:12px;border-radius:8px;margin:8px 0;">
    영 제30조제4항에 따라 수의계약 체결 시 견적서 제출을 생략할 수 있는 경우는 다음 각 호의 경우로 한다.

    1. 전기, 가스, 수도 등의 공급계약을 체결하는 경우
    2. <strong>추정가격이 200만원 미만</strong>인 물품의 제조·구매·임차 및 용역 계약을 체결하는 경우
    3. 추정가격이 200만원 미만인 물품을 「여신전문금융업법」에 따른 신용카드로 구매하는 경우
    4. 국가 및 다른 지방자치단체와 수의계약을 체결하는 경우
    </div>

    ### 펜스 설치 견적 절차

    | 추정가격 | 견적서 제출 | 견적 업체 수 |
    |---|---|---|
    | 200만원 미만 | 생략 가능 (시행규칙 §33 2호) — 단 펜스는 통상 "공사"라 §33 2호 직접 적용 곤란, 200만원 미만 공사는 사실상 드묾 |
    | 200만원 ~ 2,000만원 | 1인 견적 가능 (영 §30 ① 1호) | 1개 업체 |
    | 2,000만원 초과 ~ 2억원(전문공사) | 2인 견적 (영 §30 ① 2호) | 2개 이상 업체 |
    | 2억원 초과 (전문공사) | 일반입찰 (법 §9 본문) | 공고를 통한 경쟁 |

    > **공사**(펜스 설치 포함)의 견적서 제출 생략은 시행규칙 §33 2호의 "물품" 대상이 아니므로 일반적으로 적용되지 않습니다. 본 시행규칙 §33은 주로 물품·용역에 적용됩니다.
