    | 가설펜스 (공사현장 임시) | 통상 본 공사에 포함 | 별도 분리발주 시 위 기준 적용 |

    > 시행령 §25 ① 5호 가의 "전문공사 2억원"은 단일 도급 기준입니다. 단일 펜스 설치를 부당 분할하여 수의계약 한도 내로 맞추는 것은 시행령 §77 (수의계약 부당분할 금지) 위반입니다.

    ### 시행령 §25 ① 5호 가 외 수의계약 사유 (참고)

    펜스 한도 초과 시에도 다음 사유에 해당하면 수의계약 가능:

    - **§25 ① 1호** — 천재지변·긴급복구 등 입찰 여유가 없는 경우
    - **§25 ① 4호 가·나** — 직전 시공자 책임 구분 곤란 또는 작업 혼잡으로 경쟁 불가
    - **§25 ① 4호 마** — 특허공법·신기술 적용 펜스로 사실상 경쟁 불가
