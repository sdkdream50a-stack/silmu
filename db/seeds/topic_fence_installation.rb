    ## 지방계약법 제9조 (계약의 방법)

    <div style="background:#dbeafe;padding:12px;border-radius:8px;margin:8px 0;">
    ① 지방자치단체의 장 또는 계약담당자는 계약을 체결하려면 이 법에 특별한 규정이 있는 경우를 제외하고는 일반입찰에 부쳐야 한다. 다만, 계약의 목적·성질·규모 및 지역특수성 등을 고려하여 필요하다고 인정될 때에는 대통령령으로 정하는 바에 따라 참가자의 자격을 제한하거나 참가자를 지명하여 입찰에 부치거나 수의계약에 의할 수 있다.
    </div>

    ### 펜스 설치 발주의 법적 위치

    펜스 설치 공사는 「건설산업기본법」상 통상 **전문공사** (조경시설물설치공사업, 금속구조물·창호공사업 등)에 해당합니다. 따라서 계약 방식 결정은 다음 순서로 검토합니다.

    1. **추정가격 산정** — 자재비 + 노무비 + 경비 + 일반관리비 + 이윤 + 부가가치세
    2. **공종 분류 확인** — 일반공사 / 전문공사 / 그 밖의 공사
    3. **법 §9 단서** → **시행령 §25** 수의계약 가능 사유 검토
    4. **시행규칙 §33** 견적서 제출 생략 가능 여부 확인

    > 펜스 종류와 설치 환경(도로·학교·시설 경계·공사 현장)에 따라 적용되는 부수 법령이 달라집니다. 산업안전보건법, 도로법, 어린이보호구역 규칙 등은 본문 하단 「부수 의무」에서 안내합니다.
