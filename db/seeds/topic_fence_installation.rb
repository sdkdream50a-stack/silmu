    |---|---|---|
    | 보안·경계 펜스 (강철·메쉬) | 전문공사 (금속구조물·창호공사업) | 추정가격 ≤ 2억원 |
    | 학교 운동장·교문 펜스 | 전문공사 (금속구조물·창호공사업) | 추정가격 ≤ 2억원 |
