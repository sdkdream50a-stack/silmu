    ## 증빙·집행 실무 규정

    **증빙 요건 (감사원 결산검사 및 행안부 운영기준)**

    | 증빙 항목 | 필수 여부 | 비고 |
    |---|---|---|
    | 카드매출전표 (신용카드) | 필수 | 가맹점명·일시·금액·승인번호 식별 가능해야 함 |
    | 집행품의서 | 필수 | 사용 목적·참석자(직위·인원)·예상 금액 사전 결재 |
    | 사용내역서 / 정산서 | 필수 | 실제 사용일·장소·참석자·금액·증빙 첨부 |
    | 영수증 (현금 사용 시) | 필수 | 가급적 회피, 카드 결제 우선 |
    | 결재 라인 | 필수 | 부서장·기관장 결재 |

    **금지 행위 (감사 적발 패턴)**

    <div style="background:#fee2e2;padding:12px;border-radius:8px;margin:8px 0;">
    ❌ <b>심야·휴일 사용</b>: 공식 업무 시간 외 사용은 사적 유용 의심 — 사전 승인·정당한 사유 명시 필요
    ❌ <b>특정 가맹점 반복 사용</b>: 동일 매장 단기 다회 사용은 친목 모임·사적 유용 의심
    ❌ <b>본인·가족 식사·경조사</b>: 「지방재정법」 제47조 목적 외 사용 — 전액 환수
    ❌ <b>현금 격려금 지급</b>: 업무추진비로 직원에게 현금 격려금 지급은 「공무원 보수규정」 위반 (격려금은 포상금 등 별도 과목)
    ❌ <b>취임식 화환·메달·기념품</b>: 사교의례 목적이라도 운영기준상 명시된 한도·항목만 허용
    ❌ <b>출장 시 식사·교통비 처리</b>: 출장경비는 「공무원 여비 규정」(여비 목)으로 집행해야 하며 업무추진비 처리 시 목 혼용
    </div>

    **위반 시 처분**

    | 위반 유형 | 처분 |
    |---|---|
    | 사적 유용 | 전액 환수 + 징계(지방공무원법 §69·국가공무원법 §78), 형사 처벌(횡령 등) 가능 |
    | 목 혼용 | 전액 환수 또는 시정 + 기관 평가 감점 |
    | 한도 초과 | 초과분 환수 |
    | 증빙 미비 | 환수 또는 보완 요구 + 감사 지적 |
    | 카드 포인트 미세입 | 세입조치 + 감사 지적 |

    **지방회계법 제34조 (일상경비 지급)**

    <div style="background:#eff6ff;padding:12px;border-radius:8px;margin:8px 0;">
    업무추진비를 현금으로 지급해야 할 특별한 경우 「지방회계법」 제34조에 따라 일상경비 출납원이 현금 지급할 수 있으나, 신용카드 사용 원칙은 행안부 운영기준에 따라 우선 적용됩니다.
    </div>
