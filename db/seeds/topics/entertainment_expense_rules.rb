    ## 업무추진비 집행 세부 기준 (행안부/기재부 운영기준)

    **목 분류 (세출예산 목별 집행기준 기준)**

    <div style="background:#dcfce7;padding:12px;border-radius:8px;margin:8px 0;">
    <b>업무추진비</b>는 기관운영 관련 사교적 경비(간담회·격려·접대 등)로, <b>일반수용비·여비·시설비 등 다른 목과 명확히 구분</b>됩니다.

    - <b>기관운영업무추진비</b>: 기관장·간부 사교·격려 등
    - <b>시책추진업무추진비</b>: 특정 시책 추진을 위한 외부 협의·간담회 등
    - <b>정원가산업무추진비</b>: 정원 기준 산정 항목
    </div>

    **공무원 행동강령 제14조 (금품등 수수 한도) — 대통령령**

    <div style="background:#eff6ff;padding:12px;border-radius:8px;margin:8px 0;">
    <b>제14조 ①항</b>: 공무원은 직무 관련 여부에 관계없이 동일인으로부터 <b>1회 100만원 또는 매 회계연도 300만원</b>을 초과하는 금품등을 받을 수 없습니다.

    <b>제14조 ③항 2호</b>: 원활한 직무수행·사교의례·부조 목적으로 제공되는 음식물·경조사비·선물은 중앙행정기관의 장이 정하는 <b>가액 범위</b> 안에서만 허용 — 청탁금지법 시행령 별표 1 음식물·선물·경조사비 한도 준수 의무.

    ※ 업무추진비로 외부에 제공할 때도 동일 한도가 적용됩니다 (공직자등에 대한 제공 시).
    </div>

    **표준 한도 (행안부 운영기준 기준, 매년 갱신)**

    | 항목 | 표준 한도 | 비고 |
    |---|---|---|
    | 1인 식사비 (간담회) | 행안부/기재부 매년 고시 단가 | 최근 단가는 운영기준 확인 |
    | 경조사비 (외부 제공) | 청탁금지법 시행령 한도 | 매년 시행령 개정 확인 |
    | 화환·조화 | 청탁금지법 시행령 한도 | 경조사비 한도 내 |
    | 격려금·포상금 | 별도 예산과목(포상금)으로 집행 | 업무추진비로 현금 격려금 지급 ❌ |

    ※ 위 표는 일반 기준이며, 정확한 단가·한도는 매 회계연도 「지방자치단체 예산편성 운영기준」(행안부) 또는 「예산 및 기금운용계획 집행지침」(기재부)에서 확인 필수.

    **신용카드 사용 의무**

    <div style="background:#fee2e2;padding:12px;border-radius:8px;margin:8px 0;">
    업무추진비는 원칙적으로 <b>클린카드(기관 명의 공용카드)</b>로 결제해야 하며, 부득이한 경우 개인카드 선결제 후 사후 정산할 수 있습니다. 개인카드 사용 시 <b>포인트·마일리지는 세입조치</b> 의무가 있으며, 미세입 시 감사 적발 사유입니다.
    </div>
