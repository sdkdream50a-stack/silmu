    ## 지방재정법 제47조 / 국가재정법 제45조 (예산의 목적 외 사용금지)

    <strong>지방재정법 제47조 (예산의 목적 외 사용금지)</strong>

    <div style="background:#dbeafe;padding:12px;border-radius:8px;margin:8px 0;">
    지방자치단체의 장은 세출예산에서 정한 목적 외의 용도로 경비를 사용할 수 없다.
    </div>

    <strong>국가재정법 제45조 (예산의 목적 외 사용금지)</strong>

    <div style="background:#dbeafe;padding:12px;border-radius:8px;margin:8px 0;">
    각 중앙관서의 장은 세출예산이 정한 목적 외에 경비를 사용할 수 없다.
    </div>

    <div style="background:#fef3c7;padding:12px;border-radius:8px;margin:8px 0;">
    📌 <b>핵심 원칙</b>: 업무추진비는 「세출예산 목별 집행기준」(행안부·기재부)에 따라 <b>지정된 목·세목</b>으로만 집행해야 합니다. 예) 출장 식사를 업무추진비로 처리(여비 목 혼용), 경조사비를 일반수용비로 처리 등은 모두 「지방재정법」 제47조 / 「국가재정법」 제45조 위반에 해당합니다.
    </div>

    <strong>지방재정법 제3조 / 국가재정법 제16조 (재정 운용 기본원칙)</strong>

    <div style="background:#eff6ff;padding:12px;border-radius:8px;margin:8px 0;">
    지방자치단체는 재정을 <b>건전하고 효율적으로</b> 운용하여야 하며(지방재정법 §3①), 정부는 예산 편성·집행 시 재정건전성·국민부담 최소화·재정지출 성과 제고 등 원칙을 준수하여야 합니다(국가재정법 §16).
    </div>

