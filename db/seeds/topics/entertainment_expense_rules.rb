    ## 업무추진비 집행 실무 팁

    **집행 전 체크리스트**

    ✅ 「지방자치단체 예산편성 운영기준」(행안부, 매년 개정) 또는 「예산 및 기금운용계획 집행지침」(기재부) 최신 버전 확인
    ✅ 사전 집행품의서 결재 — 사용 목적·일시·장소·참석자(소속·직위·인원)·예상 금액
    ✅ 클린카드(공용카드) 사용 가능 여부 확인 — 가맹점 등록 매장
