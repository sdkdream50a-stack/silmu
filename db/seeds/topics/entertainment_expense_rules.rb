    ## 자주 묻는 질문

    **Q. 출장 중 식사비를 업무추진비로 처리해도 되나요?**
    A. 안 됩니다. 출장 식사비는 「공무원 여비 규정」에 따른 <b>여비 목</b>으로 집행해야 하며, 업무추진비로 처리하면 「지방재정법」 제47조 / 「국가재정법」 제45조의 <b>예산의 목적 외 사용금지</b> 위반입니다. silmu 운영 DB에 등록된 감사 사례(budget-item-wrong-travel)에서 동일 위반으로 환수·시정 처분된 바 있습니다.

    **Q. 업무추진비로 직원 격려금을 현금으로 줄 수 있나요?**
    A. 안 됩니다. 격려금은 「공무원수당 등에 관한 규정」 또는 별도 포상금 과목으로 집행해야 하며, 업무추진비로 현금 지급하는 것은 목 혼용 + 「공무원 보수규정」 위반입니다. 감사 사례(goe-2021-business-promotion-improper)에서 격려금·취임식 화분·메달·현금 지급이 모두 부적정 처분되었습니다.

    **Q. 경조사비 한도가 정확히 얼마인가요?**
    A. 청탁금지법 시행령 별표 1의 가액 한도가 적용되며, 시행령은 <b>매년 또는 비정기적으로 개정</b>됩니다. 최근 기준은 「국민권익위원회」 또는 「법제처 국가법령정보센터」에서 「부정청탁 및 금품등 수수의 금지에 관한 법률 시행령」 별표 1을 확인하세요. 한도 초과 시 「공무원 행동강령」 제14조 위반에 해당합니다.

    **Q. 개인카드로 결제하고 영수증 처리하면 안 되나요?**
