    ❌ <b>이자·보험료·채권압류금 분류 혼동</b> — 종류별 구분 미준수 (AuditCase: goe-2021-suspense-cash-management)
    ❌ <b>학교발전기금을 세입세출외현금으로 관리</b> — 기부금 분류 오류, 별도 회계 처리 의무 (AuditCase: goe-2021-development-fund-misclassified)
    ❌ <b>퇴직적립금 세외 관리 부적정</b> — 교육공무직 DB형 퇴직연금 운용 규정 위반 (AuditCase: goe-2021-retirement-pension-mismanagement)
