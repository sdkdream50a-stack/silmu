    ## 관리·결재 절차 및 감사 패턴

    **출납원의 책임과 결재 라인**

    | 단계 | 담당 | 내용 |
    |---|---|---|
    | 수납 | 세입세출외현금 출납원 | 종류·금액·납부자·사유 기록 |
    | 보관 | 금고(은행) | 종류별 구분 계좌 또는 분리 보관 |
    | 결재 | 회계책임관·통합지출관 | 2인 이상 결재 의무 (1인 결재 ❌) |
    | 지급·환부 | 권리자 청구 → 결재 후 지급 | 청구서·증빙·신분 확인 |
