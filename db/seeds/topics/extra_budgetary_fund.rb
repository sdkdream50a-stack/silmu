    ## 세입세출외현금 관리 실무 팁

    **수납 단계 체크리스트**

    ✅ 종류(보증금/보관금/기부금/이자 등) 명확히 구분 — 합산 ❌
    ✅ 납부자·금액·사유·날짜 일자별 기록
    ✅ 금고 입금 계좌 분리 — 일반 세입계좌와 혼합 금지
    ✅ 수납 즉시 출납부 등재 — 일자 지연 시 횡령 위험

    **결재·승인 단계**

    ✅ 2인 이상 결재 원칙 — 출납원 단독 처리 절대 금지 ([[AuditCase: goe-2021-suspense-cash-single-approval]])
    ✅ 회계책임관(또는 통합지출관) 결재 라인 확보
    ✅ 정원 3명 이내 관서는 분임재무관과 일상경비등 출납원 겸직 가능 (시행령 §46) — 세입세출외현금 출납원은 별도

    **유가증권 처리**

    ✅ 입찰·계약 보증금을 유가증권으로 받을 경우 금고 보관 예외 가능 (시행령 §51③)
    ✅ 그 외 유가증권은 세입세출외현금 출납원이 금고 보관
    ✅ 조례·규칙으로 유가증권 취급 공무원 별도 지정 가능

    **결산 단계**

    ✅ 회계연도 종료 시 종류별·연도별 잔액 결산서 명시
    ✅ 금고 검사(연 1회 이상) 시 출납상황·장부 일치 확인 (시행령 §50)
    ✅ 다음 회계연도 이월 시 종류별 구분 유지

    **자주 발생하는 함정**

    ⚠️ <b>학교발전기금 처리</b> — 「초·중등교육법」에 따른 별도 회계, 세입세출외현금이 아님 (AuditCase: goe-2021-development-fund-misclassified)
    ⚠️ <b>이자 발생 시 처리</b> — 보관금 운용 이자는 종류별 귀속 명확히 (이자 자체가 세입세출외현금)
    ⚠️ <b>채권압류금</b> — 압류 사실·해제 시점 기록 필수
    ⚠️ <b>퇴직적립금</b> — 교육공무직 등 DB형 연금은 운용기관 위탁이 원칙, 세외 관리 부적정 패턴 다발
    ⚠️ <b>회계연도 종료 임박 미정산</b> — 보관금·이자 등 결산 누락 → 감사 지적

