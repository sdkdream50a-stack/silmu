    ## 지방회계법 제44조 (출납원) — 세입세출외현금 출납원의 근거

    <strong>지방회계법 제44조 (출납원)</strong>

    <div style="background:#dbeafe;padding:12px;border-radius:8px;margin:8px 0;">
    <b>제1항</b>: 출납원은 지방자치단체의 장이나 그 위임을 받은 공무원이 소속 공무원 중에서 임명한다.

    <b>제2항</b>: 출납원은 법령, 조례 및 규칙에서 정하는 바에 따라 현금이나 물품을 출납·보관하여야 한다.

    <b>제3항</b>: 출납원은 수입대체경비 출납원, 수입금출납원, 일상경비등 출납원, <b>세입세출외현금 출납원</b> 및 물품 출납원 등으로 구분한다.
    </div>

    <strong>지방회계법 제42조 (공금 취급의 제한) / 제43조 (현금 취급의 제한)</strong>

    <div style="background:#fef3c7;padding:12px;border-radius:8px;margin:8px 0;">
    <b>제42조</b>: 지방자치단체의 장은 공금의 징수·수납·보관·관리·지출 사무를 <b>법령에서 정한 자 또는 법령에 따라 위임받은 자 외의 자</b>에게 취급하게 할 수 없다.

    <b>제43조</b>: 지방자치단체의 자금은 <b>대통령령으로 정하는 경우 외에는 현금으로 보관하거나 지급할 수 없다</b> (금고 보관·계좌 입출금 원칙).
    </div>

    <strong>지방회계법 제39조 (세계현금의 전용)</strong>

    <div style="background:#eff6ff;padding:12px;border-radius:8px;margin:8px 0;">
    지방자치단체는 회계처리를 할 때 세계현금(歲計現金)이 부족한 경우 같은 회계연도에서만 다른 회계로부터 자금을 전용할 수 있으며, 전용한 자금은 그 회계연도의 수입으로 변제하여야 합니다.
    </div>

    <div style="background:#f3f4f6;padding:12px;border-radius:8px;margin:8px 0;">
    📌 <b>위임 체계</b>: 지방회계법 제44조(법률, 출납원 분류) → 지방회계법 시행령 제51조(세입세출외현금 금고 보관 의무)·제52조(현금 취급 예외) → 행정안전부령 및 지자체 조례·규칙에서 종류별 처리 절차 규정.
    </div>

    <div style="background:#f3f4f6;padding:12px;border-radius:8px;margin:8px 0;">
    ⚖️ <b>관련 법령</b>: 지방회계법 제42조·제43조·제44조·제39조·제40조(금고 검사), 지방회계법 시행령 제50조~제52조, 「공무원의 직무에 관한 법률」, 「지방자치단체 회계관리에 관한 훈령」.
    ⚠️ 국가 회계는 「국고금관리법」 및 「국고금관리법 시행령」의 보관금 처리 규정이 별도로 적용됩니다.
    </div>
