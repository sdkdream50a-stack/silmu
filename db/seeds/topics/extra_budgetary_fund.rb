    ## 세입세출외현금의 종류·관리 (지방회계법 시행령)

    **지방회계법 시행령 제51조 (세입세출 외 현금 및 유가증권 등의 금고보관)**

    <div style="background:#dcfce7;padding:12px;border-radius:8px;margin:8px 0;">
    <b>제1항</b>: 지방자치단체의 세입세출 외 현금은 <b>세입세출외현금 출납원이 종류별로 명확히 구분하여 금고에 보관</b>하여야 하며, 연도 구분은 그 수입과 지출을 한 날이 속하는 연도에 따른다.

    <b>제2항</b>: 지방자치단체가 소유하거나 보관하는 <b>유가증권</b>은 조례·규칙으로 따로 지정된 경우를 제외하고 세입세출외현금 출납원이 취급·금고 보관한다.

    <b>제3항</b>: 다만, <b>계약업무 관련 보증금</b>을 유가증권으로 제출하는 경우에는 금고에 보관하지 않을 수 있다.
    </div>

    **세입세출외현금의 대표 유형**

    | 유형 | 예시 | 처리 원칙 |
    |---|---|---|
    | <b>입찰·계약 보증금</b> | 입찰보증금, 계약보증금, 하자보수보증금 | 종료 시 반환 또는 세입 처리 |
    | <b>보관금</b> | 영치금, 압수물 매각대금, 채권압류금 | 권리자 청구 시 지급 |
    | <b>예치금·예수금</b> | 공탁금, 강제집행 보관금 | 법령 절차에 따른 반환 |
    | <b>기부금</b> | 지정 기부금(예: 학교발전기금) | 지정 목적 외 사용 금지 |
    | <b>퇴직적립금</b> | 교육공무직 DB형 퇴직연금 | 지정 운용기관 위탁 |
    | <b>이자·보험료·정산금</b> | 예금이자, 산재·고용보험료 환급금 | 발생 즉시 종류별 구분 |

    **지방회계법 시행령 제52조 (현금 취급 제한의 예외)**

    <div style="background:#eff6ff;padding:12px;border-radius:8px;margin:8px 0;">
    다음 경우에만 현금 사용 허용:
    1. 계좌 입금 및 카드 사용이 불가능한 경우
    2. 일직비·숙직비 지급
    3. 업무추진비 중 격려금, 조의금, 축의금 지급
    4. 공무원의 여비 지급
    5. 그 밖에 행정안전부장관이 정하는 경비

    → 세입세출외현금 보관·지급도 원칙적으로 <b>금고 계좌</b> 사용. 현금 보관은 위 사유에 한정.
    </div>

    **회계 결산 시 처리**

    - 회계연도 종료 시 세입세출외현금 잔액·내역을 결산서에 명시
    - 금고는 연 1회 이상 검사(지방회계법 시행령 §50)
    - 종류별 분리·연도별 구분 의무 — 일괄 합산 처리 ❌
