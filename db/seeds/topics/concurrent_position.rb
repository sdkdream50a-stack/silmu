    ## 자주 묻는 질문

    **Q. 영리 업무와 겸직의 가장 큰 차이는 무엇인가요?**
    A. **영리 업무**(지방공무원 복무규정 §10 / 국가공무원 복무규정 §25)는 4가지 유형(경영·임원·투자·계속적 재산 이득)에 해당하면 **원천 금지**입니다. 허가로 면제되지 않습니다. **겸직**(복무규정 §11/§26)은 영리 업무에 **해당하지 않는** 다른 직무로, **소속 기관장의 사전 허가**를 받으면 가능합니다.

    **Q. 부동산 임대업도 영리업무로 금지되나요?**
    A. 본인 소유 1~2채의 단순 임대(상속·결혼 등으로 보유)는 일반적으로 §10·§25 4호의 "계속적 재산 이득"으로 보지 않습니다. 다만 **사업자등록·다수 임대·임대업 적극 운영**이면 영리업무로 판단될 수 있습니다. 인사·감사 부서에 사전 상담 권장.

    **Q. 학회·협회의 이사를 맡으려고 합니다. 어떤 절차가 필요한가요?**
    A. **비영리** 학회·협회 이사는 영리업무에 해당하지 않으므로 **겸직 허가**(지방 §11 / 국가 §26) 대상입니다. 사전에 소속 기관장(단체장·지방의회 의장·임용권자)에게 겸직허가 신청서를 제출해야 합니다. **영리** 사기업의 이사·감사는 §10 2호·§25 2호로 **절대 금지**입니다.

    **Q. 외부강의 사례금이 5만원입니다. 신고해야 하나요?**
    A. 「부정청탁 및 금품등 수수의 금지에 관한 법률」 제10조에 따라 **사례금 액수와 무관하게 직무 관련 외부강의는 신고 의무**입니다. 사례금이 무료라도 신고 대상이며, 상한액(시간당 40만원, 1시간 초과 시 시간당 30만원 — 기관별 변동 가능)을 초과하면 위반입니다. 자세한 기준은 「청탁금지법」 시행령과 소속 기관 규정 확인.

