    ## 겸직 허가 절차 (지방공무원 복무규정 §11 · 국가공무원 복무규정 §26)

    **「지방공무원 복무규정」 제11조 (겸직 허가)**

    <div style="background:#eff6ff;padding:12px;border-radius:8px;margin:8px 0;">
    ① 공무원이 §10의 **영리업무에 해당하지 아니하는 다른 직무**를 겸직하려는 경우에는 **지방자치단체의 장이나 지방의회 의장의 사전 허가**를 받아야 합니다.
    ② 허가는 **담당직무 수행에 지장이 없는 경우에만** 할 수 있습니다.
    </div>

    **「국가공무원 복무규정」 제26조 (겸직 허가)**

    <div style="background:#eff6ff;padding:12px;border-radius:8px;margin:8px 0;">
    ① 영리 업무에 해당하지 않는 다른 직무는 **소속 기관의 장 사전 허가** 필수.
    ② 담당 직무 수행에 **지장이 없는 경우에만** 허가.
    ③ "**소속 기관의 장**" 정의:
       - 고위공무원단 이상 → **임용제청권자**
       - 3급 이하 공무원 및 우정직공무원 → **임용권자**
    </div>
