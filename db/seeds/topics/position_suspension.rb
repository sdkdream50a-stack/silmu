    ## 수당 처리 (지방공무원 수당규정 제19조)

    <div style="background:#eff6ff;padding:12px;border-radius:8px;margin:8px 0;">
    **「지방공무원 수당 등에 관한 규정」 제19조 ⑤**: 직위해제 기간에는 다음 수당을 **지급하지 아니합니다**:
    - 특수지근무수당
    - 위험근무수당
    - 특수업무수당 (단, 교원의 보전수당은 별표 4 예에 따라 감액지급)
    - §18~§18의6의 실비변상 등

    **월중 직위해제 또는 복직**의 경우: 실제 근무한 일수에 따라 **일할계산** 지급.
    </div>

    ## 처분 취소 시 소급 지급

    <div style="background:#fee2e2;padding:12px;border-radius:8px;margin:8px 0;">
    **「지방공무원 보수규정」 제29조 ①**: 직위해제처분이 **무효·취소 또는 변경**된 경우(징계의결 요구에 따른 직위해제처분은 제외) → 복귀일에 **원래 정기승급일 기준 보수 전액 또는 차액을 소급 지급**.

    **수당규정 제19조 ⑦**: 소청심사·법원 판결로 처분이 취소·변경된 경우 수당도 소급 지급. 단 **시간외근무수당·야간근무수당·휴일근무수당·관리업무수당·정액급식비·연가보상비**는 **소급 지급하지 않습니다**(실제 근무에 따라 지급되는 수당이기 때문).
    </div>
