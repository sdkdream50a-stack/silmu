    ## 자주 묻는 질문

    **Q. 직위해제와 정직의 가장 큰 차이는 무엇인가요?**
    A. 직위해제는 **처분이 아닌 임시 조치**입니다. 사유가 소멸되면 직위를 다시 부여해야 합니다. 봉급도 50~80% 일부 지급됩니다. 반면 정직은 **징계 처분**으로, 1~3개월 직무 정지 + **봉급 전액 미지급**입니다(공무원보수규정 등). 또한 정직 후 18개월간 승진·승급 제한이 따릅니다.

    **Q. 형사사건으로 기소되면 무조건 직위해제되나요?**
    A. 임용권자의 재량입니다(「국가공무원법」 §73의3 ①4호, 「지방공무원법」 §65의3 ①3호: "직위를 부여하지 **아니할 수 있다**"). 다만 약식명령 청구는 직위해제 사유에서 제외됩니다. 비위 정도, 정상 업무 수행 가능성, 사회적 영향 등을 고려해 결정합니다.

    **Q. 직위해제 중에 소청심사를 청구하면 봉급이 다시 100% 지급되나요?**
    A. 아닙니다. 소청심사 청구만으로는 **집행이 정지되지 않습니다**. 소청심사위원회 또는 법원이 처분을 **취소·변경**해야 봉급 차액이 **소급 지급**됩니다(「지방공무원 보수규정」 §29 ①). 다만 시간외근무수당·야간근무수당·정액급식비 등 실제 근무 기준 수당은 소급되지 않습니다(수당규정 §19 ⑦).

    **Q. 3개월 대기명령 후에도 능력이 회복되지 않으면 어떻게 되나요?**
    A. 「지방공무원법」 §62 ①4호 또는 「국가공무원법」 §70 ①4호에 따라 **직권면직** 사유가 됩니다. 절차는 인사위원회 의결을 거쳐야 하며, 직위해제 → 3개월 대기명령 → 교육훈련·연구과제 부여(§65의3 ④) → 회복 미흡 → 직권면직 순으로 진행됩니다.

    **Q. 직위해제 기간은 승진·승급에 반영되나요?**
    A. 원칙적으로 **승급기간에 산입되지 않으며**, 승진소요 최저연수에서도 제외됩니다. 다만 직위해제 처분이 소청·판결로 **취소·변경**된 경우에는 「지방공무원 보수규정」 §14 ④, §29 ②에 따라 승급기간에 산입될 수 있고, 이 경우 정기승급일 기준 보수 차액을 소급 지급합니다.

    **Q. 직위해제와 징계가 동시에 진행될 수 있나요?**
