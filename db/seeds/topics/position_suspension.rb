    **소청심사 청구**

    | 단계 | 내용 |
    |-----|------|
    | 청구 기관 | **지방**: 시·도 인사위원회 / **국가**: 소청심사위원회 |
    | 청구 기간 | 처분사유 설명서 수령일부터 **30일 이내** |
    | 청구 효과 | **집행 정지 효력 없음** (직위해제 처분은 그대로 진행) |
    | 인용 시 | 처분 취소 → 봉급·수당 차액 **소급 지급** (보수규정 §29·수당규정 §19 ⑦) |

    **승급·경력 평정 처리**

