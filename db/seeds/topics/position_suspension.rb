    ## 지방공무원법 제65조의3 (직위해제) — 지방공무원

    **「지방공무원법」 제65조의3 (직위해제)**

    <div style="background:#dbeafe;padding:12px;border-radius:8px;margin:8px 0;">
    임용권자는 다음 각 호의 어느 하나에 해당하는 사람에 대하여는 직위를 부여하지 아니할 수 있습니다(제1항):

    | 호 | 사유 | 봉급 감액 |
    |----|------|-----------|
    | **1호** | 직무수행 능력이 부족하거나 근무성적이 극히 나쁜 사람 | 봉급의 **80%** |
    | **2호** | 파면·해임·강등·정직에 해당하는 **징계의결이 요구**되고 있는 사람 | 봉급의 **50%** (3개월 후 30%) |
    | **3호** | **형사사건으로 기소**된 사람(약식명령 청구는 제외) | 봉급의 **50%** (3개월 후 30%) |
    | **4호** | 금품비위·성범죄 등 대통령령으로 정하는 **비위행위로 수사 중**인 자로서 비위의 정도가 중대하고 정상적인 업무수행을 기대하기 현저히 어려운 자 | 봉급의 **50%** (3개월 후 30%) |

    제2항: 직위해제 사유가 소멸되면 지체 없이 직위를 부여하여야 합니다.
    제3항: **제1호 사유**(능력부족·성적불량)로 직위해제할 때에는 미리 해당 **인사위원회의 의견**을 들어야 하며, **3개월의 범위에서 대기**를 명합니다.
    제4항: 대기명령을 받은 사람에게는 능력 회복·근무성적 향상을 위한 **교육훈련 또는 특별 연구과제 부여** 등 필요 조치를 하여야 합니다.
    제5항: 제1호 사유와 제2~4호 사유가 **경합할 때에는 제2~4호 처분**을 하여야 합니다(중한 처분 우선).
    </div>

    ## 국가공무원법 제73조의3 (직위해제) — 국가공무원

    **「국가공무원법」 제73조의3 (직위해제)** — 지방공무원법 제65조의3과 거의 동일하나 **고위공무원단 적격심사** 사유가 추가됩니다:

    <div style="background:#eff6ff;padding:12px;border-radius:8px;margin:8px 0;">
    | 호 | 사유 | 봉급 감액 |
    |----|------|-----------|
    | 2호 | 직무수행 능력 부족·근무성적 불량 | **80%** |
    | 3호 | 징계의결 요구 중 | **50%** (3개월 후 30%) |
    | 4호 | 형사기소(약식명령 제외) | **50%** (3개월 후 30%) |
    | **5호** | 고위공무원단 일반직으로 **적격심사 요구** | **70%** (3개월 후 40%) |
    | 6호 | 비위행위 수사 중 | **50%** (3개월 후 30%) |

    ※ 제1호는 삭제됨. 제5호는 국가공무원 고유 사유로 지방공무원에는 없습니다.
    </div>

