    ## 직위해제 절차 및 후속 조치

    **직위해제 처분 절차**

    <div style="background:#dbeafe;padding:12px;border-radius:8px;margin:8px 0;">
    1. **사유 확인** (능력 부족·징계의결 요구·기소·수사 중 등)
    2. **인사위원회 의견 청취** (지방공무원법 §65의3 ①1호 사유에 한정 — 의무 절차)
    3. **직위해제 처분장 통보** (사유·근거 법령·기간 명시)
    4. **보수 감액 시행** (보수규정 §28·§29에 따라 봉급·수당 자동 감액)
    5. **(1호 사유) 3개월 대기명령** + 능력 회복 교육훈련·연구과제 부여
    6. **사유 소멸 시 직위 부여** (지체 없이) 또는 **직권면직 연계** (능력 회복 안 됨)
    </div>

    **§65의3 ①1호 → 직권면직 연계**

    <div style="background:#fee2e2;padding:12px;border-radius:8px;margin:8px 0;">
    능력 부족·성적 불량 사유로 직위해제된 사람이 3개월 대기명령 기간에도 능력 회복·근무성적 향상이 없으면 **「지방공무원법」 제62조 ①4호** 또는 **「국가공무원법」 제70조 ①4호**에 따른 **직권면직** 사유가 됩니다.

    절차: 직위해제(§65의3 ①1호) → 3개월 대기명령(§65의3 ③) → 교육훈련·과제 부여(§65의3 ④) → 회복 미흡 → 인사위원회 의결 → 직권면직.
