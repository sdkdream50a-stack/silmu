    ## 자주 묻는 질문

    **Q. 시간외근무수당 시간당 단가는 어떻게 계산하나요?**
    A. **봉급기준액 × (1/209) × 150%** 산식입니다(「지방공무원 수당 등에 관한 규정」 제15조 ②, 「공무원수당 등에 관한 규정」 제15조 ②). 봉급기준액은 본인 기준호봉 봉급액의 55%(일반) 또는 60%(8급 이하 일부)입니다. 예를 들어 봉급기준액 2,200,000원이면 시간당 약 15,790원이 됩니다. 기준호봉은 지방은 별표 11, 국가는 별표 12를 참조합니다.

    **Q. 평일에 19시까지 일하면 몇 시간이 시간외 인정되나요?**
    A. 평일 시간외근무시간은 **해당 일 시간외에서 1시간을 뺀** 시간이 인정됩니다(수당규정 §15 ⑤항 2호 나목). 예를 들어 18시 정시 퇴근 시각 기준 19시까지 근무하면 1시간이지만 -1시간 공제로 **0시간**이 됩니다. 또한 1일 시간외 합계가 **1시간 미만이면 합산 자체가 안 됩니다**. 토·공휴일은 -1시간 공제 없이 시간 그대로 인정됩니다.

    **Q. 야간·휴일근무수당은 모든 공무원이 받나요?**
    A. **아닙니다.** 야간근무수당(§16)과 휴일근무수당(§17)은 **현업공무원등**(상시근무체제 유지·토일정상근무 기관 소속, 「지방공무원 복무규정」 §5)에 한정됩니다. 일반 공무원은 야간·휴일에 근무해도 **시간외근무수당(§15)** 으로 통합 지급받습니다. 다만 휴일·토요일은 시간외 산정 시 -1시간 공제 없이 그대로 인정됩니다.

    **Q. 월 57시간을 초과해서 일하면 그 초과분도 받을 수 있나요?**
    A. 원칙적으로 **불가**합니다. 수당규정 §15 ④항은 **1일 4시간, 월 57시간**을 시간외근무명령 한도로 정합니다. 예외는 ①현업공무원등 ②재난·재해 발생 시 ③행정안전부장관·인사혁신처장이 정한 불가피 사유뿐입니다. 한도를 초과한 근무는 보상되지 않으며, 무리한 초과근무명령은 별도 책임 문제가 됩니다.

    **Q. 시간외근무수당을 부정 수령하면 어떻게 되나요?**
    A. 매우 엄격합니다. **부정 수령액의 5배에 해당하는 금액을 가산 징수**(§15 ⑧항)하며, **1년 범위에서 적발 횟수에 따라 시간외근무명령 자체를 안 받게** 됩니다. **2회 이상 적발 시 인사위원회·징계위원회에 징계의결 요구 의무**가 발생합니다. 방과후수업 강사수당·자율학습감독수당 등과 중복 청구하는 경우가 대표 적발 유형입니다(GOE 2021 감사 사례 다수).

    **Q. 정년퇴직월의 시간외수당은 어떻게 계산하나요?**
    A. 정년·명예퇴직 시 1일 이상 근무하면 **정액분(월 10시간) 전액**을 받을 수 있는 특례가 있습니다. 자세한 내용은 「시간외수당 퇴직월 특례」 토픽(slug=`edu-overtime-retirement-month`)을 참고하세요. 일반 일할 기준(15일)과 다른 점에 유의해야 합니다.
