    ## 복직 시 처우 — 신분·호봉·경력

    **복직자 신분 보장 (지방공무원법 §65① / 국가공무원법 §73①)**

    <div style="background:#eff6ff;padding:12px;border-radius:8px;margin:8px 0;">
    - 휴직 중에도 신분 유지 → 복직 시 별도 임용 절차 없이 직위 복귀
    - 휴직 기간 만료 후 30일 이내 복귀 신고 시 <b>당연 복직</b> (임용권자 발령 불요)
    - 사유 소멸 후 30일 이내 신고 의무 위반 시 무단결근으로 간주, 징계 사유
    - 복직 시 원직위 또는 동일·유사 직위 배치 의무
    </div>

    **복직 후 호봉·경력 산입 (요지)**

    | 휴직 사유 | 호봉 승급 | 경력(승진소요연수) 산입 |
    |---|---|---|
    | 질병휴직(공무상) | 산입 | 산입 |
    | 질병휴직(일반) | 산입 비율 일부 제한 | 산입 비율 일부 제한 |
