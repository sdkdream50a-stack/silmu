    ## 지방공무원법 제65조 / 국가공무원법 제73조 (휴직의 효력) — 복직의 근거

    <strong>지방공무원법 제65조 (휴직의 효력)</strong>

    <div style="background:#dbeafe;padding:12px;border-radius:8px;margin:8px 0;">
    <b>제1항</b>: 휴직 중인 공무원은 공무원의 신분은 보유하나 직무에 종사하지 못한다.

    <b>제2항</b>: 휴직 중인 공무원은 휴직기간 중 그 사유가 소멸되면 30일 이내에 임용권자에게 신고하여야 하며, 임용권자는 지체 없이 복직을 명하여야 한다.

    <b>제3항</b>: 휴직기간이 끝난 공무원이 30일 이내에 복귀신고를 하면 당연히 복직된다.
    </div>

    <strong>국가공무원법 제73조 (휴직의 효력) — 동등 규정</strong>

    <div style="background:#eff6ff;padding:12px;border-radius:8px;margin:8px 0;">
    국가공무원법 제73조는 지방공무원법 제65조와 동일한 효력 구조를 가집니다 — 휴직 중 신분 유지(①), 사유 소멸 시 30일 이내 신고·복직 명령(②), 휴직기간 만료 후 30일 이내 복귀 신고 시 당연 복직(③).
