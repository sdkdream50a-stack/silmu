    ## 휴직 사유별 복직 처리 (공무원임용령 등)

    **휴직 종료·복직 결정 흐름**

    <div style="background:#dcfce7;padding:12px;border-radius:8px;margin:8px 0;">
    1. 휴직 사유 소멸 또는 휴직 기간 만료 — 본인이 사유 확인
    2. 30일 이내에 임용권자(또는 임용제청권자)에게 복귀(복직) 신고
    3. 복직 신청서 + 사유 소멸 증빙(예: 진단서·전역증·자녀 양육 종료 등) 제출
    4. 임용권자의 복직 명령(휴직 기간 만료 후 신고분은 당연 복직)
    5. e-사람 인사발령 등록 → 원직위 또는 동일·유사 직위 배치

    근거: 「지방공무원법」 제65조제2항·제3항 / 「국가공무원법」 제73조제2항·제3항
    </div>

    **휴직 사유별 복직 시점·요건 (대표 사례)**

    | 휴직 사유 | 지방 근거 | 국가 근거 | 복직 시점·요건 |
    |---|---|---|---|
    | 질병휴직 | 지방공무원법 §63①1 | 국가공무원법 §71①1 | 치유·요양 종료 진단서 제출 후 신고 |
    | 병역휴직 | 지방공무원법 §63①2 | 국가공무원법 §71①3 | 전역·소집해제일로부터 30일 이내 신고 |
    | 육아휴직 | 지방공무원법 §63②4 | 국가공무원법 §71②4 | 휴직 기간 만료 또는 자녀 양육 사유 종료 |
    | 가족돌봄휴직 | 지방공무원법 §63②5 | 국가공무원법 §71②5 | 돌봄 필요성 종료 또는 기간 만료 |
    | 동반휴직 | 지방공무원법 §63②6 | 국가공무원법 §71②6 | 배우자 귀국·임지 변경 등 |
    | 민간근무휴직 | 지방공무원법 §63②1 | 국가공무원법 §71②1·공무원임용령 §57 | 채용계약 종료 또는 위반에 따른 복직 요청·명령 |

    ※ 휴직기간은 「지방공무원법」 제64조에 직접 명시(질병 1년 이내·연장 1년, 공무상 부상 3년 이내·연장 2년, 육아휴직 자녀 1명당 3년 이내, 동반휴직 3년 이내 연장 2년 등). 국가공무원의 경우 휴직기간은 「공무원임용령」에 따라 별도 적용.

    **민간근무휴직자 복직 (공무원임용령 제57조)**

    <div style="background:#eff6ff;padding:12px;border-radius:8px;margin:8px 0;">
    <b>제57조 ①항</b>: 민간기업등의 장은 휴직공무원의 근무태만·채용계약 위반·복무규율 위반 등으로 계속 채용할 수 없는 경우 소속 장관에게 복직을 요청할 수 있습니다.

    <b>제57조 ②항</b>: 소속 장관은 ①항 요청을 받거나 휴직공무원이 임용령 제54조제2항~제5항 위반·징계의결 요구·형사기소(약식명령 제외) 등 사유 발생 시 복직을 명할 수 있습니다.
    </div>
