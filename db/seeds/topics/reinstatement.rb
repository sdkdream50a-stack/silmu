    | 복직 예정 통보 | 복직 예정일 30일 전 소속 기관(인사부서) 통보 권장 |
    | 복직 신청서 제출 | 복직 예정일 전 신청서 + 사유 소멸 증빙 첨부 |
    | 기관장 복직 발령 | e-사람(국가직) / 새올행정시스템 등(지방직) 인사발령 등록·원직위/유사 직위 배치 |
