# quick_stats 는 jsonb 라 문자열 치환이 아니라 행 단위로 고친다.
QUICK_STATS_NOTE = [ "지방계약법 시행령 제77조제3항",
                     "공사: 시행령 제77조제3항 / 물품·용역: 시행령 제7조제2호·행안부 예규" ].freeze

TEXT_FIELDS = %i[name summary law_content decree_content rule_content regulation_content
                 practical_tips interpretation_content qa_content verification_source audit_cases].freeze
JSON_FIELDS = %i[faqs howto_steps].freeze
CASE_FIELDS = %i[title issue detail legal_basis lesson action_taken].freeze

changed = Hash.new(0)

sub = lambda do |v|
  s = v.dup
  SUBS.each { |old, new| s = s.gsub(old, new) if s.include?(old) }
  s
end

Topic.find_each do |t|
  dirty = false
  # ⚠️ Topic#audit_cases 는 같은 이름의 has_many 연관이 컬럼을 가린다.
  # public_send 로 쓰면 연관을 Hash 로 덮어써 AssociationTypeMismatch 가 난다(실측).
  # 컬럼은 read_attribute/write_attribute 로만 다룬다.
  (TEXT_FIELDS + JSON_FIELDS).each do |f|
    next unless t.has_attribute?(f.to_s)
    v = t.read_attribute(f)
    next if v.blank?
    if v.is_a?(String)
      nv = sub.call(v)
      next if nv == v
      t.write_attribute(f, nv)
    else
      raw = v.to_json
      nv = sub.call(raw)
      next if nv == raw
      t.write_attribute(f, JSON.parse(nv))
    end
    dirty = true
    changed["#{t.slug}##{f}"] += 1
  end

  if t.has_attribute?("quick_stats") && t.read_attribute(:quick_stats).present?
    raw_qs = t.read_attribute(:quick_stats)
    qs = raw_qs.is_a?(String) ? JSON.parse(raw_qs) : raw_qs
    hit = false
    qs = qs.map do |row|
      r = row.dup
      if r["label"].to_s.include?("수의 회피 금지") && r["note"].to_s == QUICK_STATS_NOTE[0]
        r["note"] = QUICK_STATS_NOTE[1]
        hit = true
      end
      r
    end
    if hit
      t.write_attribute(:quick_stats, raw_qs.is_a?(String) ? qs.to_json : qs)
      dirty = true
      changed["#{t.slug}#quick_stats"] += 1
    end
  end

  t.save! if dirty
end

if defined?(AuditCase)
  AuditCase.find_each do |a|
    dirty = false
    CASE_FIELDS.each do |f|
      next unless a.respond_to?(f)
      v = a.public_send(f)
      next unless v.is_a?(String) && v.present?
      nv = sub.call(v)
      next if nv == v
      a.public_send("#{f}=", nv)
      dirty = true
      changed["AuditCase##{a.id}##{f}"] += 1
    end
    a.save! if dirty
  end
end

puts "정정 필드: #{changed.size}"
changed.sort.each { |k, v| puts "  ✓ #{k} (#{v})" }
