  ## 초·중등교육법 시행령

  초·중등교육법 시행령에는 학교회계 예산편성·집행 절차 조문이 없습니다. 법 제30조의2⑤·제30조의3⑥에 따라 국립학교는 교육부령(「국립유치원 및 초ㆍ중등학교 회계규칙」), 공립학교는 시·도 교육규칙(학교회계 규칙)에서 정합니다.

  예산편성과 함께 자주 찾는 시행령 조문은 학교발전기금입니다.

  ### 제64조(학교발전기금) 중 ①·②

  ① 법 제33조의 규정에 의한 학교발전기금(이하 "발전기금"이라 한다)은 다음 각호의 방법에 의하여 조성한다.
  1. 기부자가 기부한 금품의 접수
  2. 학부모 등으로 구성된 학교내ㆍ외의 조직ㆍ단체 등이 그 구성원으로부터 자발적으로 갹출하거나 구성원외의 자로부터 모금한 금품의 접수

  ② 발전기금은 다음 각호의 목적을 위하여 사용한다.
  1. 학교교육시설의 보수 및 확충
  2. 교육용 기자재 및 도서의 구입
  3. 학교체육활동 기타 학예활동의 지원
  4. 학생복지 및 학생자치활동의 지원
MD

