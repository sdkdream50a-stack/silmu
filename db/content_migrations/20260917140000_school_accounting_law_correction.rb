deep_sub = lambda do |value, from, to|
  case value
  when String then value.gsub(from, to)
  when Array  then value.map { |v| deep_sub.call(v, from, to) }
  when Hash   then value.transform_values { |v| deep_sub.call(v, from, to) }
  else value
  end
end

contains = lambda do |value, needle|
  case value
  when String then value.include?(needle)
  when Array  then value.any? { |v| contains.call(v, needle) }
  when Hash   then value.values.any? { |v| contains.call(v, needle) }
  else false
  end
end

dry_run = ENV["DRY_RUN"] == "1"
applied = 0

ActiveRecord::Base.transaction do
  topic = Topic.find_by!(slug: "school-budget-compilation")
  topic_replace.each do |column, (fingerprint, replacement)|
    current = topic.public_send(column).to_s
    next if current == replacement # 멱등

    raise "FABRICATED_TEXT_NOT_FOUND school-budget-compilation/#{column}" unless current.include?(fingerprint)

    topic.update_columns(column => replacement, updated_at: Time.current) unless dry_run
    applied += 1
  end

  subs.each do |klass, slug, column, pairs|
    record = klass.find_by!(slug: slug)
    value = record.public_send(column)
    pairs.each do |from, to|
      next if to.present? && contains.call(value, to) && !contains.call(value, from)
      unless contains.call(value, from)
        next if to.empty? # 삭제형 치환은 이미 지워졌으면 멱등
        raise "STALE_TEXT_NOT_FOUND #{klass.name}/#{slug}/#{column}: #{from[0, 40]}"
      end

      value = deep_sub.call(value, from, to)
      applied += 1
    end
    record.update_columns(column => value, updated_at: Time.current) unless dry_run
  end

  puts "  [school-accounting] #{dry_run ? 'DRY_RUN ' : ''}changes=#{applied}"
  raise ActiveRecord::Rollback if dry_run
end
