  ## 학교회계 규칙 (교육부령·시도 교육규칙)

  초·중등교육법 시행규칙에는 학교회계 조문이 없습니다. 예산 과목, 이용·전용, 이월, 결산 서류는 아래 규칙에서 정합니다.

  - **국립학교**: 「국립유치원 및 초ㆍ중등학교 회계규칙」(교육부령)
  - **공립학교**: 시·도 교육규칙(예: ○○도 공립학교회계 규칙) — 소속 교육청 규칙 원문을 확인하세요.

  ### 국립유치원 및 초ㆍ중등학교 회계규칙 제20조(세출예산의 이월) — 원문

  ① 세출예산 중 경비의 성질상 해당회계연도 내에 지출을 끝내지 못할 것이 예상되어 명시이월비로서 특히 그 취지를 세입ㆍ세출예산에 명시하여 학교운영위원회의 심의를 거친 경비는 다음 회계연도에 이월하여 사용할 수 있다.

  ② 세출예산 중 해당회계연도 내에 지출원인행위를 하고 불가피한 사유로 인하여 해당회계연도 내에 지출하지 못한 경비(지출원인행위를 하지 않은 부대경비를 포함한다)의 금액은 사고이월비로서 다음 회계연도에 이월하여 사용할 수 있다.

  ③ 계속비의 연도별 소요경비의 금액 중 해당회계연도 내에 지출하지 못한 금액은 해당계속비의 사업완성연도까지 차례로 이월하여 사용할 수 있다.
