count_in = lambda do |value, needle|
  case value
  when String then value.scan(needle).size
  when Array  then value.sum { |v| count_in.call(v, needle) }
  when Hash   then value.values.sum { |v| count_in.call(v, needle) }
  else 0
  end
end

leaf_count = lambda do |value, leaf|
  case value
  when String then value == leaf ? 1 : 0
  when Array  then value.sum { |v| leaf_count.call(v, leaf) }
  when Hash   then value.values.sum { |v| leaf_count.call(v, leaf) }
  else 0
  end
end

replace_in = lambda do |value, from, to|
  case value
  when String then value.gsub(from) { to }
  when Array  then value.map { |v| replace_in.call(v, from, to) }
  when Hash   then value.transform_values { |v| replace_in.call(v, from, to) }
  else value
  end
end

delete_leaf = lambda do |value, leaf|
  case value
  when Array then value.reject { |v| v == leaf }.map { |v| delete_leaf.call(v, leaf) }
  when Hash  then value.transform_values { |v| delete_leaf.call(v, leaf) }
  else value
  end
end

