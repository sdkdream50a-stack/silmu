  ## 공무원 여비 규정 주요 조문 (원문)

  ### 공무원 여비 규정 제3조(여비의 지급 구분)

  국가공무원(이하 “공무원”이라 한다)의 여비는 별표 1의 여비 지급 구분표에 따라 지급한다.

  ### 공무원 여비 규정 제13조(자동차운임의 지급)

  ① 국내 자동차운임은 별표 2에 따라 지급한다.

  ② 국외 자동차운임은 실비로 지급한다.

  ### 공무원 여비 규정 제16조(일비ㆍ숙박비ㆍ식비의 지급)

  ① 국내 여행자의 일비(日費)ㆍ숙박비 및 식비는 별표 2에 따라 지급하고, 국외 여행자의 경우는 별표 4에 따라 지급한다. 다만, 공무의 형편이나 그 밖의 부득이한 사유로 숙박비의 상한액 및 지급받은 식비(국내 여행의 경우 식비는 제외한다)를 초과하여 여비를 지출하였을 때에는 국내 여행의 경우에는 숙박비 상한액의 10분의 3을, 국외 여행의 경우에는 숙박비 및 식비의 2분의 1을 넘지 아니하는 범위에서 여비를 추가로 지급할 수 있다.

  ② 제1항 단서에 따라 여비를 추가로 지급받으려는 공무원은 여행을 마친 날의 다음 날부터 기산하여 1주일 이내(국외 여행의 경우에는 2주일 이내를 말한다)에 정부구매카드 또는 신용카드를 사용하고 받은 매출전표에 세부 사용내용이 명시된 증거자료를 갖추어 회계 관계 공무원에게 정산을 신청하여야 한다.

  ③ 일비는 여행일수에 따라 지급하되, 공무용 차량을 이용하는 경우 등 인사혁신처장이 정하는 바에 따라 여행을 하는 경우에는 일비의 2분의 1을 지급한다.

  ④ 숙박비는 숙박하는 밤의 수에 따라 지급한다. 다만, 수로여행과 항공여행에는 숙박비를 지급하지 아니하되, 천재지변이나 그 밖의 부득이한 사유로 육지에서 숙박할 필요가 있는 경우에는 숙박비를 지급한다.

  ⑤ 식비는 여행일수에 따라 지급한다. 다만, 수로여행과 항공여행에는 따로 식비가 필요한 경우에만 식비를 지급한다.

  ### 공무원 여비 규정 제18조(근무지 내 국내 출장 시의 여비)

  ① 근무지 내 국내 출장의 경우에는 제16조에도 불구하고 출장 여행시간이 4시간 이상인 공무원에게는 2만원을 지급하고, 4시간 미만인 공무원에게는 1만원을 지급한다. 다만, 「공무용 차량 관리 규정」 제4조 및 별표에 따른 전용 차량 배정자에게는 이를 지급하지 않으며, 공무용 차량을 이용하는 경우 등 인사혁신처장이 정하는 바에 따라 출장을 하는 공무원에게는 1만원을 감액하여 지급한다.

  ② 제1항에서 “근무지 내 국내 출장”이란 다음 각 호의 어느 하나에 해당하는 출장을 말한다.
  1. 같은 시(특별시, 광역시 및 특별자치시를 포함한다. 이하 같다)ㆍ군 및 섬(제주특별자치도는 제외한다. 이하 같다) 안에서의 출장. 이 경우 통합특별시는 종전의 전라남도 관할구역의 시ㆍ군 및 광주광역시를 기준으로 적용한다.
  2. 여행거리가 12킬로미터 미만인 출장

  일비·식비·숙박비 금액과 자동차운임 기준은 같은 규정 별표 2(국내 여비 지급표)에 있습니다.

