count_in = lambda do |value, needle|
  case value
  when String then value.scan(needle).size
  when Array  then value.sum { |v| count_in.call(v, needle) }
  when Hash   then value.values.sum { |v| count_in.call(v, needle) }
  else 0
  end
end

replace_in = lambda do |value, from, to|
  case value
  when String then value.gsub(from) { to }
  when Array  then value.map { |v| replace_in.call(v, from, to) }
  when Hash   then value.transform_values { |v| replace_in.call(v, from, to) }
  else value
  end
end

slugs = (laws.keys + edits.map(&:first)).uniq
dry = ENV["DRY_RUN"] == "1"
changes = 0
ActiveRecord::Base.transaction(requires_new: true) do
  slugs.each do |slug|
    guide = Guide.find_by(slug: slug)
    next unless guide

    to_write = {}
    %w[sections rich_media].each do |field|
      original = guide.read_attribute(field)
      original = original.deep_stringify_keys if original.is_a?(Hash)
      value = original

      if field == "sections" && laws.key?(slug)
        old_laws, new_laws = laws[slug]
        current = Array(value["laws"]).map { |l| l.is_a?(Hash) ? l.deep_stringify_keys : l }
        unless current == new_laws
          raise "[guide-source-budget] laws fingerprint mismatch: #{slug}" unless current == old_laws

          value = value.merge("laws" => new_laws)
          changes += 1
        end
      end

      edits.select { |s, f, _, _| s == slug && f == field }.each do |_, _, old, new|
        # 이미 적용됨: new 가 있고 old 가 없거나, new 가 old 를 품는 덧붙임형 edit(«(실무 관행)» 표시 등)
        next if count_in.call(value, new).positive? && (count_in.call(value, old).zero? || new.include?(old))
        raise "[guide-source-budget] fingerprint missing: #{slug}/#{field}: #{old[0, 40]}" unless count_in.call(value, old) == 1

        value = replace_in.call(value, old, new)
        changes += 1
      end
      to_write[field] = value unless value == original
    end
    next if to_write.empty?

    puts "  [guide-source-budget] Guide/#{slug} fields_to_change=#{to_write.keys.join(',')}"
    guide.update_columns(to_write.merge("updated_at" => Time.current)) unless dry
  end
end
puts "  [guide-source-budget] #{"DRY_RUN " if dry}changes=#{changes}"
